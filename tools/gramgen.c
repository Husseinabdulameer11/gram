/*
 * gramgen - turn a grammar file into a C starting point (host tool).
 *
 *   gramgen lang.gram prefix [outdir]
 *
 * writes
 *   <prefix>_grammar.h   rule-id enum + the grammar as a C string.
 *   <prefix>_grammar.c   the same grammar already compiled, as const
 *                        tables (`<prefix>_grammar`) that can live in ROM.
 *                        Regenerate both whenever the grammar changes.
 *   <prefix>_visitor.c   a tree walker with one `case` per rule, ready to
 *                        fill in. Only written if it does not exist yet.
 */
#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../gram.h"

static void put_file(int c, void *ctx) { fputc(c, (FILE *)ctx); }

static char *slurp(const char *path)
{
    FILE *f = fopen(path, "rb");
    char *buf;
    long n;
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    n = ftell(f);
    fseek(f, 0, SEEK_SET);
    buf = (char *)malloc((size_t)n + 1);
    if (buf && fread(buf, 1, (size_t)n, f) != (size_t)n) { free(buf); buf = NULL; }
    if (buf) buf[n] = 0;
    fclose(f);
    return buf;
}

static void upper(char *dst, const char *src)
{
    while (*src) *dst++ = (char)toupper((unsigned char)*src++);
    *dst = 0;
}

static void emit_string(FILE *o, const char *s)
{
    fputs("    \"", o);
    for (; *s; s++) {
        if (*s == '\n') { fputs("\\n\"", o); if (s[1]) fputs(" \\\n    \"", o); }
        else if (*s == '\r') continue;
        else if (*s == '"' || *s == '\\') { fputc('\\', o); fputc(*s, o); }
        else if (*s == '\t') fputs("\\t", o);
        else if (*s == '?') fputs("\\?", o); /* no accidental trigraphs */
        else fputc(*s, o);
    }
    if (s[-1] != '\n') fputc('"', o);
    fputc('\n', o);
}

/* ---- precompiled tables ------------------------------------------------ */

static const gram_x **nodes;
static int nnodes, capnodes;

static void collect(const gram_x *x)
{
    const gram_x *k;
    if (nnodes == capnodes) {
        capnodes = capnodes ? capnodes * 2 : 256;
        nodes = (const gram_x **)realloc((void *)nodes, (size_t)capnodes * sizeof *nodes);
        if (!nodes) { fprintf(stderr, "gramgen: out of memory\n"); exit(1); }
    }
    nodes[nnodes++] = x;
    for (k = x->kid; k; k = k->next) collect(k);
}

static int node_index(const gram_x *x)
{
    int i;
    for (i = 0; i < nnodes; i++) if (nodes[i] == x) return i;
    return -1;
}

static void emit_ref(FILE *o, const gram_x *x)
{
    if (x) fprintf(o, "&x[%d]", node_index(x)); else fputc('0', o);
}

static void emit_cstr(FILE *o, const char *s)
{
    if (!s) { fputc('0', o); return; }
    fputc('"', o);
    for (; *s; s++) {
        unsigned char ch = (unsigned char)*s;
        if (ch == '"' || ch == '\\') fprintf(o, "\\%c", ch);
        else if (ch == '?') fputs("\\?", o);
        else if (ch < 32 || ch > 126) fprintf(o, "\\%03o", ch);
        else fputc(ch, o);
    }
    fputc('"', o);
}

static void emit_tables(FILE *o, const gram_grammar *g, const char *prefix, const char *src)
{
    static const char *const ops[] = { "lit", "class", "any", "call", "seq", "alt",
                                       "star", "plus", "opt", "and", "not", "drop" };
    int i;
    size_t k, n;

    for (i = 0; i < g->nrules; i++) collect(g->rules[i].body);

    fprintf(o, "/* Generated by gramgen from %s - do not edit.\n"
               " * The grammar, already compiled. Pass &%s_grammar to gram_parse();\n"
               " * no gram_compile() and no arena space for the grammar needed. */\n", src, prefix);
    fprintf(o, "#include \"gram.h\"\n#include \"%s_grammar.h\"\n\n", prefix);
    fprintf(o, "#if GRAM_TABLES != %d\n#error \"regenerate this file with the gramgen "
               "that matches gram.h\"\n#endif\n\n", GRAM_TABLES);

    for (i = 0; i < nnodes; i++) { /* literal bytes and class bitmaps */
        const gram_x *x = nodes[i];
        n = x->op == 0 ? x->n : x->op == 1 ? 32 : 0;
        if (!n) continue;
        fprintf(o, "static const unsigned char d%d[] = {", i);
        for (k = 0; k < n; k++) fprintf(o, "%s%u", k ? "," : "", (unsigned)x->data[k]);
        fprintf(o, "};\n");
    }

    fprintf(o, "\nstatic const gram_x x[%d] = {\n", nnodes);
    for (i = 0; i < nnodes; i++) {
        const gram_x *x = nodes[i];
        int has_data = (x->op == 0 && x->n) || x->op == 1;
        fprintf(o, "    /* %3d %-5s */ {%u, %u, ", i, ops[x->op], (unsigned)x->op, (unsigned)x->ci);
        emit_ref(o, x->kid);
        fputs(", ", o);
        emit_ref(o, x->next);
        fputs(", ", o);
        emit_cstr(o, x->spell);
        if (has_data) fprintf(o, ", d%d, ", i); else fputs(", 0, ", o);
        fprintf(o, "%lu}%s\n", (unsigned long)x->n, i + 1 < nnodes ? "," : "");
    }
    fprintf(o, "};\n\nstatic const gram_rule rules[%d] = {\n", g->nrules);
    for (i = 0; i < g->nrules; i++) {
        const gram_rule *r = &g->rules[i];
        fprintf(o, "    {\"%s\", ", r->name);
        emit_ref(o, r->body);
        fprintf(o, ", %lu, %u, %u, 0}%s\n", (unsigned long)r->pos, (unsigned)r->kind,
                (unsigned)r->nullable, i + 1 < g->nrules ? "," : "");
    }
    fprintf(o, "};\n\nconst gram_grammar %s_grammar = { rules, %d, %d };\n",
            prefix, g->nrules, g->skip);
}

int main(int argc, char **argv)
{
    static unsigned char mem[1 << 20];
    char path[1024], up[256];
    const char *prefix, *dir;
    gram_arena arena;
    gram_error err;
    gram_grammar *g;
    char *text;
    FILE *o;
    int i, n;

    if (argc == 2 && strcmp(argv[1], "--version") == 0) {
        printf("gramgen %s\n", GRAM_VERSION);
        return 0;
    }
    if (argc < 3 || strlen(argv[2]) >= sizeof up) {
        fprintf(stderr, "usage: gramgen lang.gram prefix [outdir]\n"
                        "       gramgen --version\n");
        return 2;
    }
    prefix = argv[2];
    dir = argc > 3 ? argv[3] : ".";
    upper(up, prefix);

    text = slurp(argv[1]);
    if (!text || !*text) { fprintf(stderr, "gramgen: cannot read %s\n", argv[1]); return 1; }

    gram_arena_init(&arena, mem, sizeof mem);
    g = gram_compile(&arena, text, &err);
    if (!g) {
        fprintf(stderr, "%s:", argv[1]);
        gram_error_print(&err, put_file, stderr);
        return 1;
    }
    n = gram_rule_count(g);

    sprintf(path, "%.900s/%.100s_grammar.h", dir, prefix);
    o = fopen(path, "w");
    if (!o) { perror(path); return 1; }
    fprintf(o, "/* Generated by gramgen from %s - do not edit. */\n", argv[1]);
    fprintf(o, "#ifndef %s_GRAMMAR_H\n#define %s_GRAMMAR_H\n\n", up, up);
    fprintf(o, "/* gram_node.rule values (rule ids are in definition order) */\nenum {\n");
    for (i = 0; i < n; i++)
        fprintf(o, "    %s_R_%s = %d,\n", up, gram_rule_name(g, i), i);
    fprintf(o, "    %s_R_COUNT = %d\n};\n\n", up, n);
    fprintf(o, "/* pass this to gram_compile(); uses %lu bytes of arena on this host */\n",
            (unsigned long)arena.peak);
    fprintf(o, "#define %s_GRAMMAR \\\n", up);
    emit_string(o, text);
    fprintf(o, "\n/* the same grammar precompiled into const tables (%s_grammar.c) */\n", prefix);
    fprintf(o, "extern const struct gram_grammar %s_grammar;\n", prefix);
    fprintf(o, "\n#endif\n");
    fclose(o);
    printf("wrote %s\n", path);

    sprintf(path, "%.900s/%.100s_grammar.c", dir, prefix);
    o = fopen(path, "w");
    if (!o) { perror(path); return 1; }
    emit_tables(o, g, prefix, argv[1]);
    fclose(o);
    printf("wrote %s\n", path);

    sprintf(path, "%.900s/%.100s_visitor.c", dir, prefix);
    o = fopen(path, "r");
    if (o) {
        fclose(o);
        printf("kept  %s (already exists)\n", path);
        return 0;
    }
    o = fopen(path, "w");
    if (!o) { perror(path); return 1; }
    fprintf(o, "/* Skeleton generated by gramgen from %s - yours to edit. */\n", argv[1]);
    fprintf(o, "#include \"gram.h\"\n#include \"%s_grammar.h\"\n\n", prefix);
    fprintf(o, "/* Walks the syntax tree. Each case sees one kind of node:\n"
               " *   n->text / n->len   the source text it covers\n"
               " *   n->child, ->next   its children, in source order\n"
               " * Replace the generic recursion with what your language should do. */\n");
    fprintf(o, "void %s_visit(const gram_node *n, void *ctx)\n{\n", prefix);
    fprintf(o, "    const gram_node *c;\n\n    switch (n->rule) {\n");
    for (i = 0; i < n; i++) {
        const char *name = gram_rule_name(g, i);
        if (strcmp(name, "skip") == 0) continue;
        fprintf(o, "    case %s_R_%s:\n        /* TODO */\n        break;\n", up, name);
    }
    fprintf(o, "    case GRAM_LITERAL: /* a 'literal' matched inside a syntax rule */\n"
               "        break;\n    }\n\n");
    fprintf(o, "    for (c = n->child; c; c = c->next)\n        %s_visit(c, ctx);\n}\n", prefix);
    fclose(o);
    printf("wrote %s\n", path);
    return 0;
}
